-- POST /api/orders의 Idempotency-Key. 같은 사용자(owner)가 같은 키로 다시 요청하면 새 주문을 만들지 않고 처음 결과를 돌려준다.
-- 주문 생성과 같은 트랜잭션에서 INSERT하므로, 같은 키의 동시 요청은 unique 제약에서 대기한 뒤 하나만 성공한다.
create table idempotency_keys (
    id              bigint generated by default as identity primary key,
    owner           varchar(100) not null,
    idempotency_key varchar(100) not null,
    request_hash    varchar(64)  not null,
    order_id        bigint,
    created_at      timestamp(6) not null,
    constraint uk_idempotency_keys_owner_key unique (owner, idempotency_key)
);

-- 연계 이력 감사 정보: 누가(requested_by), 어떤 방식으로(trigger_type: SYNC/RETRY), 어떤 실패 이력을 재처리했는지(retry_of),
-- 외부 시스템을 몇 번 호출했는지(attempt_count, 자동 Retry 포함).
alter table integration_history
    add column requested_by  varchar(100),
    add column trigger_type  varchar(10) not null default 'SYNC',
    add column retry_of      bigint,
    add column attempt_count int         not null default 1;

-- 같은 주문의 성공 이력 조회 (중복 Sync 방지)
create index idx_integration_history_order_status on integration_history (order_id, status);
