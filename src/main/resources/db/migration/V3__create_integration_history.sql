-- 주문 1건의 ERP/MES 연계 시도 1회 = 1행. 실패 이벤트(어느 시스템에서 어떤 오류로 실패했는지)도 함께 저장한다.
-- 주문이 삭제되어도 연계 이력은 감사 목적으로 남겨야 하므로 orders에 FK를 걸지 않는다.
create table integration_history (
    id             bigint generated by default as identity primary key,
    order_id       bigint       not null,
    status         varchar(20)  not null,
    erp_order_no   varchar(50),
    failed_system  varchar(10),
    error_type     varchar(30),
    error_message  varchar(500),
    requested_at   timestamp(6) not null,
    completed_at   timestamp(6) not null
);

create index idx_integration_history_order_id on integration_history (order_id);
create index idx_integration_history_status on integration_history (status);
